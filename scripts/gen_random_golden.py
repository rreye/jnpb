#!/usr/bin/env python3
# Author: Claude (Anthropic)
"""Generates src/test/resources/golden/random.properties: reference sequences of the
NPB linear congruential generator (NPB3.4.4), for the bit-exact test of
NPB.common.numerics.Random.

The official NPB 3.4.4 distribution, unpacked as ./NPB3.4.4 at the repository root
(not included in this repository), is required.

scripts/random_ref.f90 is compiled together with common/randdp.f90 and, separately,
with common/randi8.f90 (the reference's default RAND); both outputs must be identical
or the script aborts. The `power` routines (MG OMP), `power` with n1*n2+n3 (MG MPI) and
`ipow46` (FT) are extracted from the official sources (not copied by hand) and renamed
power2/power4. Required cross-checks:
  power2(a,n) == ipow46(a,n)  and  power4(a,n1,n2,n3) == power2(a,n1*n2+n3).

Usage:  python3 -I scripts/gen_random_golden.py     (requires gfortran)
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OMP = os.path.join(ROOT, "NPB3.4.4", "NPB3.4-OMP")
MPI = os.path.join(ROOT, "NPB3.4.4", "NPB3.4-MPI")
OUT = os.path.join(ROOT, "src", "test", "resources", "golden", "random.properties")
FFLAGS = ["-O2", "-ffp-contract=off"]


def read(p):
    with open(p, encoding="latin-1") as f:
        return f.read()


def extract(path, start_re, rename=None):
    """Text from the line matching start_re up to the next '      end' line."""
    lines = read(path).splitlines()
    i = next(k for k, l in enumerate(lines) if re.match(start_re, l, re.I))
    j = next(k for k in range(i, len(lines)) if re.match(r"^      end\s*$", lines[k], re.I))
    txt = "\n".join(lines[i:j + 1]) + "\n"
    return re.sub(r"\bpower\b", rename, txt, flags=re.I) if rename else txt


def run(tmp, tag, rand_src, routines):
    exe = os.path.join(tmp, "ref_" + tag)
    subprocess.run(["gfortran"] + FFLAGS + [os.path.join(ROOT, "scripts", "random_ref.f90"),
                    routines, rand_src, "-o", exe], check=True)
    return subprocess.run([exe], check=True, capture_output=True, text=True).stdout


def main():
    gfortran = subprocess.run(["gfortran", "--version"], capture_output=True,
                              text=True).stdout.splitlines()[0]
    with tempfile.TemporaryDirectory() as tmp:
        routines = os.path.join(tmp, "routines.f90")
        with open(routines, "w") as f:
            f.write(extract(os.path.join(OMP, "MG", "mg.f90"),
                            r"\s*double precision function power\(\s*a,\s*n\s*\)", "power2"))
            f.write(extract(os.path.join(MPI, "MG", "mg.f90"),
                            r"\s*double precision function power\(\s*a,\s*n1,", "power4"))
            f.write(extract(os.path.join(OMP, "FT", "ft.f90"),
                            r"\s*subroutine ipow46\("))
        out_dp = run(tmp, "dp", os.path.join(OMP, "common", "randdp.f90"), routines)
        out_i8 = run(tmp, "i8", os.path.join(OMP, "common", "randi8.f90"), routines)
    if out_dp != out_i8:
        sys.exit("randdp.f90 and randi8.f90 give different results: the reference is not unique")

    props = []
    cases = {}
    seq = {}
    vrn = {}
    vrnx = {}
    long_x = []
    pw, pw4 = [], []
    for line in out_dp.splitlines():
        t = line.split()
        if t[0] == "CASE":
            cases[int(t[1])] = (t[2], t[3])
        elif t[0] == "SEQ":
            seq.setdefault(int(t[1]), []).append((int(t[2]), t[3], t[4]))
        elif t[0] == "VRN":
            vrn.setdefault(int(t[1]), []).append(t[3])
        elif t[0] == "VRNX":
            vrnx[int(t[1])] = t[2]
        elif t[0] == "LONG":
            long_x.append(t[2])
        elif t[0] == "POW":
            if t[3] != t[4]:
                sys.exit("power(a,n) != ipow46(a,n): %s" % line)
            pw.append(" ".join(t[1:4]))
        elif t[0] == "POW4":
            if t[6] != "-1" and t[5] != t[6]:
                sys.exit("power(a,n1,n2,n3) != power(a,n1*n2+n3): %s" % line)
            pw4.append(" ".join(t[1:6]))
    props.append("# Generated by scripts/gen_random_golden.py; do not edit by hand.")
    props.append("# Reference: NPB 3.4.4 randdp.f90 (== randi8.f90), %s, -O2 -ffp-contract=off" % gfortran)
    props.append("# SEQ: x_i = seed after i calls to randlc(x,a) (integer); y_i = bits (hex) of the returned value.")
    props.append("cases=%s" % ",".join(str(c) for c in sorted(cases)))
    for c in sorted(cases):
        assert [r[0] for r in seq[c]] == list(range(1, 1001))
        props.append("case.%d.x0=%s" % (c, cases[c][0]))
        props.append("case.%d.a=%s" % (c, cases[c][1]))
        props.append("case.%d.x=%s" % (c, ",".join(r[1] for r in seq[c])))
        props.append("case.%d.y=%s" % (c, ",".join(r[2] for r in seq[c])))
        props.append("case.%d.vranlc.y=%s" % (c, ",".join(vrn[c])))
        props.append("case.%d.vranlc.x=%s" % (c, vrnx[c]))
    props.append("long.step=10000")
    props.append("long.x=%s" % ",".join(long_x))
    props.append("# a n result")
    for i, l in enumerate(pw):
        props.append("pow.%d=%s" % (i, l.replace(" ", ",")))
    props.append("# a n1 n2 n3 result")
    for i, l in enumerate(pw4):
        props.append("pow4.%d=%s" % (i, l.replace(" ", ",")))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(props) + "\n")
    print("-> %s (%d cases, %d pow, %d pow4, %d long samples)" % (
        os.path.relpath(OUT, ROOT), len(cases), len(pw), len(pw4), len(long_x)))


if __name__ == "__main__":
    main()
