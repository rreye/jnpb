	/** Test body, reusable (MpjGoldenClassBTest). */
	static void checkEp(String cls, int np) throws Exception {
		Properties g = load("EP", cls);
		String id = "EP " + cls + " np=" + np;
		String out = MpjLaunchTest.run("EP", cls, np, Collections.<String, String>emptyMap());
		assertTrue("SUCCESSFUL".equals(MpjLaunchTest.verification(out)),
				id + ": does not verify\n" + MpjLaunchTest.tail(out));

		Matcher gcm = Pattern.compile("No\\. Gaussian Pairs =\\s*(\\S+?)\\.?\\s*$", Pattern.MULTILINE).matcher(out);
		assertTrue(gcm.find(), id + ": gc not found\n" + MpjLaunchTest.tail(out));
		assertEquals(Double.parseDouble(g.getProperty("np" + np + ".gc")), Double.parseDouble(gcm.group(1)),
				id + ": gc (integer, exact)");

		int c = out.indexOf("Counts:");
		assertTrue(c >= 0, id + ": counters not found");
		Matcher qm = Pattern.compile("^\\s*(\\d+)\\s+(\\d+)\\.\\s*$", Pattern.MULTILINE).matcher(out.substring(c));
		int n = 0;
		while (qm.find() && n < 10) {
			assertEquals(n, Integer.parseInt(qm.group(1)), id + ": counters out of order");
			assertEquals(Long.parseLong(g.getProperty("np" + np + ".q." + n)), Long.parseLong(qm.group(2)),
					id + ": counter q" + n + " (integer, exact)");
			n++;
		}
		assertEquals(10, n, id + ": counters missing");

		Matcher sm = Pattern.compile("Sums =\\s*(\\S+)\\s+(\\S+)").matcher(out);
		assertTrue(sm.find(), id + ": Sums line not found");
		double max = 0;
		String[] key = { "sx", "sy" };
		for (int k = 0; k < 2; k++) {
			double expected = Double.parseDouble(g.getProperty("np" + np + "." + key[k]));
			double actual = Double.parseDouble(sm.group(k + 1));
			double rel = Math.abs(actual - expected) / Math.abs(expected);
			// `!(rel <= rtol)` also fails with NaN
			assertTrue(rel <= EP_SUM_RTOL, id + " " + key[k] + ": official=" + expected + " MPJ=" + actual + " relDiff="
					+ rel + " > " + EP_SUM_RTOL);
			max = Math.max(max, rel);
		}
		System.err.printf("GOLDEN-MPI %s sx,sy maxRelDiff=%.3e%n", id, max);
	}

