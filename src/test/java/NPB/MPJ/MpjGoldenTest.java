	/** Test body, reusable (MpjGoldenClassBTest). */
	static void checkFt(String kernel, String cls, int np) throws Exception {
		Properties g = load("FT", cls);
		String id = kernel + " " + cls + " np=" + np;
		int niter = Integer.parseInt(g.getProperty("np" + np + ".niter"));
		String out = MpjLaunchTest.run(kernel, cls, np, Collections.<String, String>emptyMap());
		assertTrue("SUCCESSFUL".equals(MpjLaunchTest.verification(out)),
				id + ": does not verify\n" + MpjLaunchTest.tail(out));
		Matcher m = FT_ROW.matcher(out);
		int n = 0;
		double max = 0;
		while (m.find()) {
			int it = Integer.parseInt(m.group(1));
			assertEquals(++n, it, id + ": non-consecutive iterations");
			double[] actual = { Double.parseDouble(m.group(2)), Double.parseDouble(m.group(3)) };
			String[] part = { "re", "im" };
			for (int c = 0; c < 2; c++) {
				double expected = Double.parseDouble(g.getProperty("np" + np + ".chk." + it + "." + part[c]));
				double rel = Math.abs(actual[c] - expected) / Math.abs(expected);
				// `!(rel <= rtol)` also fails with NaN
				assertTrue(rel <= FT_CHK_RTOL, id + " chk[" + it + "]." + part[c] + ": official=" + expected + " MPJ="
						+ actual[c] + " relDiff=" + rel + " > " + FT_CHK_RTOL);
				max = Math.max(max, rel);
			}
		}
		assertEquals(niter, n, id + ": number of checksums printed");
		System.err.printf("GOLDEN-MPI %s checksum maxRelDiff=%.3e (%d iterations)%n", id, max, n);
	}

