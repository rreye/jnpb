	/**
	 * RMS norms (xcr, xce) of SP, BT and LU against the official code with the same number of processes. SP MPJ numbers
	 * the components from 0 to 4 ({@code firstComponent} = 0); BT and LU MPJ, like the official code and SER, from 1 to 5.
	 */
	private static String checkNorms(String kernel, double rtol, int firstComponent, String cls, int np)
			throws Exception {
		Properties g = load(kernel, cls);
		String id = kernel + " " + cls + " np=" + np;
		String out = MpjLaunchTest.run(kernel, cls, np, Collections.<String, String>emptyMap());
		assertTrue("SUCCESSFUL".equals(MpjLaunchTest.verification(out)),
				id + ": does not verify\n" + MpjLaunchTest.tail(out));
		String[][] sections = { { "xcr", "Comparison of RMS-norms of residual" },
				{ "xce", "Comparison of RMS-norms of solution error" } };
		double max = 0;
		for (String[] sec : sections) {
			int at = out.indexOf(sec[1]);
			assertTrue(at >= 0, id + ": not found: '" + sec[1] + "'\n" + MpjLaunchTest.tail(out));
			// the official code (and the fixture) numbers from 1 to 5; SP MPJ from 0 to 4, BT MPJ from 1 to 5
			Matcher m = Pattern.compile("^\\s*(\\d)\\s+(\\S+)\\s+(\\S+)\\s+(\\S+)\\s*$", Pattern.MULTILINE)
					.matcher(out.substring(at));
			int n = 0;
			while (n < 5 && m.find()) {
				assertEquals(n + firstComponent, Integer.parseInt(m.group(1)), id + ": components out of order");
				double expected = Double.parseDouble(g.getProperty("np" + np + "." + sec[0] + "." + (n + 1)));
				double actual = Double.parseDouble(m.group(2));
				double rel = Math.abs(actual - expected) / Math.abs(expected);
				// `!(rel <= rtol)` also fails with NaN
				assertTrue(rel <= rtol, id + " " + sec[0] + "[" + (n + 1) + "]: official=" + expected + " MPJ="
						+ actual + " relDiff=" + rel + " > " + rtol);
				max = Math.max(max, rel);
				n++;
			}
			assertEquals(5, n, id + ": missing components of " + sec[0]);
		}
		System.err.printf("GOLDEN-MPI %s xcr,xce maxRelDiff=%.3e%n", id, max);
		return out;
	}
