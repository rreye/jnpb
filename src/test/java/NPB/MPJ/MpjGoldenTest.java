	static final double SP_RTOL = Double.parseDouble(System.getProperty("golden.mpi.sp.rtol", "1e-15"));
	/**
	 * BT: same as SP (xcr and xce, 5 components). With np=1, 4 and 16 it is bit for bit; with np=9 1 ulp (2.2e-16) is seen in
	 * some component, because of the reduction order (Allreduce), which MPI and MPJ do not share.
	 */
	static final double BT_RTOL = Double.parseDouble(System.getProperty("golden.mpi.bt.rtol", "1e-15"));

	/**
	 * LU: xcr, xce and xci against the official code with the same np. With np a power of 2 up to 16 (and the rest except
	 * for 1-2 ulp, measured up to 3.2e-16) it is bit for bit.
	 */
	static final double LU_RTOL = Double.parseDouble(System.getProperty("golden.mpi.lu.rtol", "1e-15"));

	private static final Pattern CG_ROW = Pattern.compile("^\\s+(\\d+)\\s+(\\S+)\\s+(\\S+)\\s*$", Pattern.MULTILINE);

