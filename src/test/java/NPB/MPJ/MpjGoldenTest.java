	/** Test body, reusable (MpjGoldenClassBTest). */
	static void checkCg(String cls, int np) throws Exception {
		Properties g = load("CG", cls);
		String id = "CG " + cls + " np=" + np;
		int niter = Integer.parseInt(g.getProperty("np" + np + ".niter"));
		String out = MpjLaunchTest.run("CG", cls, np, Collections.<String, String>emptyMap());
		assertTrue("SUCCESSFUL".equals(MpjLaunchTest.verification(out)),
				id + ": does not verify\n" + MpjLaunchTest.tail(out));

		Matcher m = CG_ROW.matcher(out);
		List<Integer> printed = new ArrayList<>();
		double max = 0;
		while (m.find()) {
			int it = Integer.parseInt(m.group(1));
			printed.add(it);
			double expected = Double.parseDouble(g.getProperty("np" + np + ".zeta." + it));
			double actual = Double.parseDouble(m.group(3));
			double rel = Math.abs(actual - expected) / Math.abs(expected);
			// `!(rel <= rtol)` also fails with NaN
			assertTrue(rel <= CG_ZETA_RTOL, id + " zeta[" + it + "]: official=" + expected + " MPJ=" + actual
					+ " relDiff=" + rel + " > " + CG_ZETA_RTOL);
			max = Math.max(max, rel);
		}
		List<Integer> want = new ArrayList<>();
		for (int it = 1; it <= niter; it++)
			if (it == 1 || it == niter || it % 5 == 0)
				want.add(it);
		assertEquals(want, printed, id + ": printed iterations");
		System.err.printf("GOLDEN-MPI %s zeta maxRelDiff=%.3e (%d iterations)%n", id, max, printed.size());
	}

